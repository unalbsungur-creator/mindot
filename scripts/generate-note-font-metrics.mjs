/**
 * `node scripts/generate-note-font-metrics.mjs` — writes
 * src/features/notes/lib/noteFontMetrics.generated.ts: each note-text
 * font's per-character advance width (thousandths of an em), read from the
 * exact WOFF files the share image and PDF embed (public/fonts/share/).
 *
 * The card text fit (features/notes/lib/cardText.ts) measures with this one
 * table on every surface — the board, previews, share images and PDFs — so
 * all of them break lines and pick sizes the same way, synchronously, with
 * no font file needed at run time. The DOM draws Geist / Fraunces (variable)
 * where the share image draws Noto Sans / Fraunces (static); measured over
 * Turkish, German and French text they differ by ±3%, which the fit's width
 * margin absorbs. Kerning is left out (it only ever narrows a line here).
 *
 * Re-run after changing a font file; `cardText.test.ts` checks the table
 * still matches the files.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const fontkit = require("fontkit");

const FONT_DIR = "public/fonts/share";
/** Measured faces; "elegant" reuses classic plus its 0.06em tracking, "typewriter"/"mono" are fixed-width. */
const FONTS = {
  modern: "NotoSans-Regular.woff",
  bold: "NotoSans-Bold.woff",
  classic: "Fraunces-Regular.woff",
  serif: "Fraunces-SemiBold.woff",
  handwritten: "Caveat-Regular.woff",
  typewriter: "GeistMono-Regular.woff",
};

const ranges = [
  [0x20, 0x7e],
  [0xa0, 0x17f],
  [0x2010, 0x2027],
  [0x2030, 0x203a],
  [0x1e9e, 0x1e9e],
  [0x20ac, 0x20ac],
  [0x2122, 0x2122],
];
const codePoints = ranges.flatMap(([from, to]) => Array.from({ length: to - from + 1 }, (_, i) => from + i));
const charset = String.fromCodePoint(...codePoints);

const tables = {};
for (const [name, file] of Object.entries(FONTS)) {
  const font = fontkit.create(readFileSync(path.join(FONT_DIR, file)));
  tables[name] = codePoints
    .map((cp) => (font.hasGlyphForCodePoint(cp) ? Math.round((font.glyphForCodePoint(cp).advanceWidth / font.unitsPerEm) * 1000) : 0))
    .join(",");
}

const out = `// Generated by scripts/generate-note-font-metrics.mjs from public/fonts/share/*.woff — do not edit by hand.
/** Every character the tables below cover, in order. */
export const NOTE_FONT_CHARSET = ${JSON.stringify(charset)};
/** Advance width per character of NOTE_FONT_CHARSET, in thousandths of an em (0 = no glyph). */
export const NOTE_FONT_ADVANCES = {
${Object.entries(tables)
  .map(([name, values]) => `  ${name}: "${values}",`)
  .join("\n")}
} as const;
`;
writeFileSync("src/features/notes/lib/noteFontMetrics.generated.ts", out);
console.log(`wrote ${codePoints.length} characters × ${Object.keys(tables).length} fonts`);
