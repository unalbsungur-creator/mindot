/**
 * The Worker entry point (wrangler.jsonc "main"): OpenNext's generated Worker
 * for every request, plus MN-01's 5-minute cron.
 *
 * `fetch` is OpenNext's own, unchanged. `scheduled` runs the moderation-alert
 * cron tick (src/features/moderation/alerts/cron.ts), which reads one KV flag
 * and touches the database only when a reminder or retry is due — and then
 * through the app itself: an in-process request to the internal route
 * (/api/internal/moderation-alerts), authorized by MODERATION_ALERT_CRON_SECRET.
 * Nothing here imports the app or a database client.
 */
// @ts-expect-error: generated by `opennextjs-cloudflare build` (npm run build:cf)
import openNextWorker from "./.open-next/worker.js";
import { moderationAlertCronTick, type AlertFlagKv } from "./src/features/moderation/alerts/cron";
import { CRON_SECRET_HEADER } from "./src/features/moderation/alerts/cronAuth";

// OpenNext's Durable Object classes, re-exported as its generated Worker does.
// @ts-expect-error: generated by `opennextjs-cloudflare build` (npm run build:cf)
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "./.open-next/worker.js";

interface WorkerEnv {
  MODERATION_ALERTS_KV?: AlertFlagKv;
  MODERATION_ALERT_CRON_SECRET?: string;
  NEXT_PUBLIC_APP_URL?: string;
  AUTH_URL?: string;
}

interface WorkerContext {
  waitUntil(promise: Promise<unknown>): void;
}

type FetchHandler = (request: Request, env: WorkerEnv, ctx: WorkerContext) => Promise<Response>;
const handler = openNextWorker as { fetch: FetchHandler };

const worker = {
  fetch: handler.fetch,

  async scheduled(_controller: unknown, env: WorkerEnv, ctx: WorkerContext): Promise<void> {
    ctx.waitUntil(
      (async () => {
        const result = await moderationAlertCronTick({
          kv: env.MODERATION_ALERTS_KV,
          now: new Date(),
          invoke: async () => {
            const origin = env.NEXT_PUBLIC_APP_URL || env.AUTH_URL || "https://mind-ot.com";
            const request = new Request(new URL("/api/internal/moderation-alerts", origin), {
              method: "POST",
              headers: { [CRON_SECRET_HEADER]: env.MODERATION_ALERT_CRON_SECRET ?? "" },
            });
            return (await handler.fetch(request, env, ctx)).ok;
          },
        });
        console.info(`[moderation-alerts] cron tick: ${result}`);
      })()
    );
  },
};

export default worker;
